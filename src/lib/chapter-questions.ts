/**
 * Robustly extract numeric chapter number from string IDs or numbers
 * Examples: "ch1" -> 1, "ch15" -> 15, "Chapter 5" -> 5, 8 -> 8
 */
export function parseChapterNumber(chapter: string | number): number {
  if (typeof chapter === "number" && !isNaN(chapter)) return chapter;
  const str = String(chapter);
  const match = str.match(/\d+/);
  return match ? parseInt(match[0], 10) : 1;
}

